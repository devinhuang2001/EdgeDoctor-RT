"""Generate the EdgeDoctor equipment image as a raw LVGL RGB565 asset."""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image


WIDTH = 440
HEIGHT = 148


def rgb565_bytes(image: Image.Image) -> bytes:
    output = bytearray()
    for red, green, blue in image.convert("RGB").getdata():
        value = ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)
        output.extend(value.to_bytes(2, "little"))
    return bytes(output)


def prepare_image(source: Path) -> Image.Image:
    image = Image.open(source).convert("RGBA")
    alpha_box = image.getchannel("A").getbbox()
    if alpha_box is not None:
        image = image.crop(alpha_box)
    image.thumbnail((WIDTH - 8, HEIGHT - 8), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (WIDTH, HEIGHT), (255, 255, 255, 255))
    x = (WIDTH - image.width) // 2
    y = (HEIGHT - image.height) // 2
    canvas.alpha_composite(image, (x, y))
    return canvas.convert("RGB")


def write_header(path: Path) -> None:
    path.write_text(
        "#ifndef EDGEDOCTOR_MACHINE_IMAGE_H\n"
        "#define EDGEDOCTOR_MACHINE_IMAGE_H\n\n"
        "#include <lvgl.h>\n\n"
        "extern const lv_image_dsc_t edgedoctor_machine_image;\n\n"
        "#endif\n",
        encoding="utf-8",
    )


def write_source(path: Path, data: bytes) -> None:
    lines = []
    for offset in range(0, len(data), 16):
        values = ", ".join(f"0x{value:02X}" for value in data[offset : offset + 16])
        lines.append(f"    {values},")
    source = f"""/* Generated by tools/generate_lvgl_machine_asset.py. */
#include "edgedoctor_machine_image.h"

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

static const LV_ATTRIBUTE_MEM_ALIGN uint8_t edgedoctor_machine_pixels[] = {{
{chr(10).join(lines)}
}};

const lv_image_dsc_t edgedoctor_machine_image = {{
    .header.w = {WIDTH},
    .header.h = {HEIGHT},
    .header.stride = {WIDTH * 2},
    .header.cf = LV_COLOR_FORMAT_RGB565,
    .data_size = sizeof(edgedoctor_machine_pixels),
    .data = edgedoctor_machine_pixels,
}};
"""
    path.write_text(source, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output_dir", type=Path)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    image = prepare_image(args.source)
    data = rgb565_bytes(image)
    write_header(args.output_dir / "edgedoctor_machine_image.h")
    write_source(args.output_dir / "edgedoctor_machine_image.c", data)
    image.save(args.output_dir / "edgedoctor_machine_preview.png")
    print(f"generated {WIDTH}x{HEIGHT}, {len(data)} bytes")


if __name__ == "__main__":
    main()
