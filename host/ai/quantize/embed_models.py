"""Embed exported TFLite artifacts and their held-out parity vectors in firmware."""
from pathlib import Path
import argparse
import json
import numpy as np
from tensorflow.lite.python import schema_py_generated as schema


def array(name: str, data: bytes) -> str:
    rows = [", ".join(str(value) for value in data[i:i + 16])
            for i in range(0, len(data), 16)]
    return (f"alignas(16) const unsigned char {name}[] = {{\n    " +
            ",\n    ".join(rows) + f"\n}};\nconst unsigned int {name}_size = sizeof({name});\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--vela", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    meta = json.loads(args.model.with_suffix(".json").read_text())
    golden = np.load(args.model.with_suffix(".golden.npz"), allow_pickle=False)
    vela_bytes = args.vela.read_bytes()
    model = schema.Model.GetRootAsModel(vela_bytes, 0)
    graph = model.Subgraphs(0)
    if graph.OperatorsLength() == 0:
        raise ValueError("Vela model has no operators")
    for index in range(graph.OperatorsLength()):
        code = model.OperatorCodes(graph.Operators(index).OpcodeIndex())
        if code.BuiltinCode() != schema.BuiltinOperator.CUSTOM or code.CustomCode() != b"ethos-u":
            raise ValueError("Expected full NPU coverage; Vela model contains a CPU operator")
    text = '// Generated by ai/quantize/embed_models.py. Do not edit.\n'
    text += '#include "ed_inference_models.h"\n'
    text += array("ed_model_cpu", args.model.read_bytes())
    text += array("ed_model_u55", vela_bytes)
    text += f'const float ed_model_input_scale = {meta["input_quantization"][0]:.10e}f;\n'
    text += f'const int ed_model_input_zero = {meta["input_quantization"][1]};\n'
    text += f'const float ed_model_output_scale = {meta["output_quantization"][0]:.10e}f;\n'
    for name, values in [("ed_model_golden_inputs", golden["inputs"]),
                         ("ed_model_golden_outputs", golden["outputs"])]:
        values = values[:200]
        text += f'const signed char {name}[{len(values)}][{values.shape[1]}] = {{\n'
        text += ",\n".join("    {" + ",".join(str(int(v)) for v in row) + "}" for row in values)
        text += '\n};\n'
    text += f'const unsigned int ed_model_golden_count = {min(200, len(golden["inputs"]))};\n'
    args.output.write_text(text)


if __name__ == "__main__":
    main()
